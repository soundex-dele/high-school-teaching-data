def _slug(point_id: str) -> str:
    return point_id.rsplit(".", 1)[-1]


def _options_with_rotated_answer(
    point_id: str,
    question_index: int,
    correct: str,
    distractors: list[str],
) -> tuple[list[dict[str, str]], str]:
    texts = [correct, *distractors]
    rotation = (sum(ord(char) for char in point_id) + question_index) % 4
    texts = texts[rotation:] + texts[:rotation]
    option_ids = ["A", "B", "C", "D"]
    return (
        [
            {"id": option_id, "text": text}
            for option_id, text in zip(option_ids, texts, strict=True)
        ],
        option_ids[texts.index(correct)],
    )


def build_questions(
    point_id: str,
    name: str,
    subject: str,
    history_topics: dict[str, list[str]],
) -> list[dict]:
    """Build five questions while preserving the public YAML shape."""
    slug = _slug(point_id)
    result: list[dict] = []

    if subject == "math":
        seeds = MATH_QUESTIONS[slug]
        for index, seed in enumerate(seeds):
            correct = seed.options[seed.answer]
            distractors = [
                text for option_index, text in enumerate(seed.options)
                if option_index != seed.answer
            ]
            options, correct_id = _options_with_rotated_answer(
                point_id, index, correct, distractors
            )
            result.append({
                "id": f"{point_id}.q{index + 1}",
                "stem": seed.stem,
                "options": options,
                "correct_option_id": correct_id,
                "explanation": seed.explanation,
                "difficulty": DIFFICULTIES[index],
                "tags": [name, "计算与推理" if index >= 2 else "概念与运算"],
                "source_type": "original",
            })
        return result

    topics = history_topics[slug]
    clues = HISTORY_CLUES[slug]
    for index, (topic, clue) in enumerate(zip(topics, clues, strict=True)):
        # Basic questions identify a topic from evidence.  Medium and advanced
        # questions reverse the task: select a defensible interpretation from
        # four same-chapter claims.  The latter cannot be answered by spotting a
        # keyword in the material.
        if index < 2:
            correct = topic
            distractors = [topics[(index + offset) % 5] for offset in (1, 2, 3)]
            stem = f"下列哪一历史主题与材料描述最吻合：“{clue}”（ ）。"
            explanation = (
                f"材料以“{clue}”为关键线索，指向“{topic}”。"
                "其余选项虽属同一章，但在时段、对象或核心机制上与材料不符。"
            )
        else:
            correct = clue
            distractors = [clues[(index + offset) % 5] for offset in (1, 2, 3)]
            stem = f"围绕“{topic}”作历史解释，下列论述最准确的是（ ）。"
            explanation = (
                f"“{clue}”准确概括了“{topic}”的时空背景、核心机制或历史影响；"
                "其余论述分别对应本章其他主题，不能替代该主题的解释。"
            )
        options, correct_id = _options_with_rotated_answer(
            point_id, index, correct, distractors
        )
        result.append({
            "id": f"{point_id}.q{index + 1}",
            "stem": stem,
            "options": options,
            "correct_option_id": correct_id,
            "explanation": explanation,
            "difficulty": DIFFICULTIES[index],
            "tags": [name, topic, "史料实证" if index >= 2 else "时空观念"],
            "source_type": "original",
        })
    return result


def validate_seed_coverage(
    math_slugs: set[str], history_slugs: set[str]
) -> None:
    if math_slugs != set(MATH_QUESTIONS):
        raise ValueError(
            f"数学题目种子覆盖不完整：{sorted(math_slugs ^ set(MATH_QUESTIONS))}"
        )
    if history_slugs != set(HISTORY_CLUES):
        raise ValueError(
            f"历史题目种子覆盖不完整：{sorted(history_slugs ^ set(HISTORY_CLUES))}"
        )
    for slug, seeds in MATH_QUESTIONS.items():
        if len(seeds) != 5:
            raise ValueError(f"{slug}: expected five math question seeds")
        for seed in seeds:
            if seed.answer not in range(4) or len(set(seed.options)) != 4:
                raise ValueError(f"{slug}: invalid answer or duplicate options in {seed.stem}")
    for slug, clues in HISTORY_CLUES.items():
        if len(clues) != 5 or len(set(clues)) != 5:
            raise ValueError(f"{slug}: expected five unique history clues")
